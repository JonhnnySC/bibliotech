--  - token salvo no banco (verificado a cada requisição)
--  - multibiblioteca (equivalente da empresa): usuario.biblioteca_id
--  - auditoria: quem registrou o empréstimo (vem do usuário logado)

CREATE TABLE IF NOT EXISTS biblioteca (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    cnpj VARCHAR(255)
);

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS biblioteca_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_biblioteca') THEN
        ALTER TABLE usuario ADD CONSTRAINT fk_usuario_biblioteca
            FOREIGN KEY (biblioteca_id) REFERENCES biblioteca (id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_usuario_biblioteca ON usuario (biblioteca_id);

CREATE TABLE IF NOT EXISTS token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token         VARCHAR(1000) NOT NULL,
    data_cadastro TIMESTAMP     NOT NULL,
    usuario_id    BIGINT        NOT NULL,
    CONSTRAINT uk_token_token UNIQUE (token),
    CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE INDEX IF NOT EXISTS idx_token_usuario ON token (usuario_id);

ALTER TABLE emprestimo ADD COLUMN IF NOT EXISTS registrado_por_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emprestimo_registrado_por') THEN
        ALTER TABLE emprestimo ADD CONSTRAINT fk_emprestimo_registrado_por
            FOREIGN KEY (registrado_por_id) REFERENCES usuario (id);
    END IF;
END $$;
